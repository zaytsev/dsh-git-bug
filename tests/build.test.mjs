import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import test from 'node:test'
import { fileURLToPath } from 'node:url'

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const read = name => readFileSync(join(ROOT, name), 'utf8')

/** One selector per rule, in source order (comments and at-rules skipped). */
function selectorsOf(css) {
  return css
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .split('\n')
    .map(line => line.trim())
    .filter(line => line.length > 0 && !line.startsWith('@'))
    .map(line => (line.includes('{') ? line.slice(0, line.indexOf('{')) : line))
    .filter(selector => selector.length > 0)
}

test('the built bundle carries every rule from the stylesheet', () => {
  const selectors = selectorsOf(read('src/client/styles.css'))
  assert.ok(selectors.length > 20, 'expected the stylesheet to have rules, got ' + String(selectors.length))
  const bundle = read('lib/client.js')
  const missing = selectors.filter(selector => !bundle.includes(selector + '{'))
  assert.deepEqual(missing, [], 'lib/client.js is stale: run npm run build')
})

test('the stylesheet is the only place CSS is authored', () => {
  const factory = read('src/client/factory.js')
  const longest = Math.max(...factory.split('\n').map(line => line.length))
  assert.ok(longest < 400, 'src/client/factory.js has a ' + String(longest) + '-char line; CSS belongs in styles.css')
  assert.doesNotMatch(factory, /const CSS = /, 'the factory must not carry a CSS literal')
  assert.doesNotMatch(factory, /const LOCALES = /, 'the factory must not carry a locale literal')
  assert.doesNotMatch(factory, /[\u4E00-\u9FFF]/, 'translated text belongs in src/client/locales/')
})

test('locale dictionaries share one key set and stay in their own language', () => {
  const en = JSON.parse(read('src/client/locales/en.json'))
  const zh = JSON.parse(read('src/client/locales/zh.json'))
  assert.deepEqual(Object.keys(zh).sort(), Object.keys(en).sort(), 'a missing key would fall back mid-sentence')
  for (const [key, value] of Object.entries(en)) {
    assert.doesNotMatch(value, /[\u4E00-\u9FFF]/u, 'en.' + key + ' must not contain CJK text')
  }
  assert.match(zh.issues, /[\u4E00-\u9FFF]/u, 'zh.issues is Chinese')
  assert.doesNotMatch(zh.issues, /Issues/, 'zh.issues is not the English caption')
  assert.notEqual(zh.search, en.search, 'the filter placeholder is translated')
})

test('labels stay on one line and the label cloud never scrolls', () => {
  const css = read('src/client/styles.css')
  assert.match(css, /\.gb-label\{[^}]*white-space:nowrap/, 'label text never breaks')
  assert.match(css, /\.gb-chip\{[^}]*white-space:nowrap/, 'chip text never breaks')
  assert.match(css, /\.gb-labels\{[^}]*flex-wrap:wrap/, 'the label group wraps between labels')
  assert.doesNotMatch(css, /\.gb-cloud\{[^}]*overflow:auto/, 'the cloud shows every label')
})

test('the build is deterministic and self-contained', () => {
  const before = read('lib/client.js')
  execFileSync(process.execPath, [join(ROOT, 'scripts/build-client.mjs')], { cwd: ROOT })
  const after = read('lib/client.js')
  assert.equal(after, before, 'a rebuild of unchanged sources must produce identical bytes')
  assert.match(after, /const CSS = "/, 'the bundle inlines the stylesheet')
  assert.match(after, /const LOCALES = \{/, 'the bundle inlines the locale dictionaries')
  const zh = JSON.parse(read('src/client/locales/zh.json'))
  assert.ok(after.includes('"issues":' + JSON.stringify(zh.issues)), 'both locales travel in the one bundle')
  assert.match(after, /^\/\* Generated by scripts\/build-client\.mjs/m, 'the bundle says it is generated')
  assert.match(after, /^window\.__ModuleLoader__\.load\(\{$/m)
})
