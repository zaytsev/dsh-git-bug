#!/usr/bin/env node
/**
 * Wrap src/client/factory.js in the client loader's registration format and
 * inline the stylesheet and locale dictionaries.
 * @module dsh-git-bug/scripts/build-client
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const ID = 'dsh-git-bug'

/** Locale ids the panel ships. English is the DSH baseline fallback. */
const LOCALE_IDS = ['en', 'zh']

const body = readFileSync(join(root, 'src/client/factory.js'), 'utf8')
if (/(^|\n)\s*(import|export)\s/.test(body)) {
  throw new Error('src/client/factory.js must be a factory body: no import/export statements')
}
if (/^\t\tconst CSS = /m.test(body)) {
  throw new Error('src/client/factory.js must not declare CSS: it is inlined from src/client/styles.css')
}
if (/^\t\tconst LOCALES = /m.test(body)) {
  throw new Error('src/client/factory.js must not declare LOCALES: it is inlined from src/client/locales/')
}
if (/[\u4E00-\u9FFF]/.test(body)) {
  throw new Error('src/client/factory.js must not carry translated text: it belongs in src/client/locales/')
}

const styles = readFileSync(join(root, 'src/client/styles.css'), 'utf8')
if (styles.trim().length === 0) throw new Error('src/client/styles.css is empty')

/**
 * Read the locale dictionaries and enforce the contract the panel relies on:
 * every locale has exactly the English key set, so a language never falls back
 * mid-sentence, and English carries no CJK text.
 */
function readLocales() {
  const locales = {}
  for (const id of LOCALE_IDS) {
    const file = join(root, 'src/client/locales', id + '.json')
    let entries
    try {
      entries = JSON.parse(readFileSync(file, 'utf8'))
    } catch (error) {
      throw new Error('cannot read ' + file + ': ' + (error instanceof Error ? error.message : String(error)))
    }
    if (typeof entries !== 'object' || entries === null || Array.isArray(entries)) {
      throw new Error(file + ' must contain one JSON object')
    }
    for (const [key, value] of Object.entries(entries)) {
      if (typeof value !== 'string' || value.trim().length === 0) {
        throw new Error(file + ': ' + key + ' must be a non-empty string')
      }
    }
    locales[id] = entries
  }
  const reference = Object.keys(locales.en).sort()
  for (const id of LOCALE_IDS) {
    const keys = Object.keys(locales[id]).sort()
    if (keys.length !== reference.length || keys.some((key, index) => key !== reference[index])) {
      throw new Error('src/client/locales/' + id + '.json: keys must match en.json exactly')
    }
    locales[id] = Object.fromEntries(reference.map(key => [key, locales[id][key]]))
  }
  if (/[\u4E00-\u9FFF]/.test(JSON.stringify(locales.en))) {
    throw new Error('src/client/locales/en.json must not contain CJK text')
  }
  return locales
}

const locales = readLocales()

const header = [
  '/* Generated by scripts/build-client.mjs from src/client/. Edit the sources, not this file. */',
  'window.__ModuleLoader__.load({',
  `\tid: ${JSON.stringify(ID)},`,
  '\tfactory: (require) => {',
  '\t\tvar module = { exports: {} };',
  '\t\tvar exports = module.exports;',
  '\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });',
  `\t\tconst CSS = ${JSON.stringify(styles)};`,
  `\t\tconst LOCALES = ${JSON.stringify(locales)};`,
  '',
].join('\n')

const footer = ['', '\t\treturn module.exports;', '\t}', '});', ''].join('\n')

const target = join(root, 'lib/client.js')
mkdirSync(dirname(target), { recursive: true })
const built = header + body + footer
writeFileSync(target, built)
process.stdout.write(`wrote ${target} (${String(built.length)} bytes, ${String(styles.length)} of CSS)\n`)
